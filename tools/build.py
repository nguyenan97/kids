"""Build static SEO parts of the site from data/videos.json (stdlib only).

Run from the repo root:  python tools/build.py
Writes: js/videos-data.js, the BUILD blocks in index.html, sitemap.xml.
Only videos that have a youtube_id AND whose publish_at is in the past go into
JSON-LD and the static list, so Google never sees a private/scheduled video.
"""
import datetime as dt
import html
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
data = json.loads((ROOT / "data/videos.json").read_text(encoding="utf-8"))
ch = data["channel"]
site = data["site_url"]
now = dt.datetime.now(dt.timezone.utc)


def is_live(v):
    return bool(v.get("youtube_id")) and dt.datetime.fromisoformat(v["publish_at"]) <= now


def watch_url(v):
    vid = v["youtube_id"]
    return f"https://www.youtube.com/shorts/{vid}" if v["type"] == "short" else f"https://www.youtube.com/watch?v={vid}"


live = [v for v in data["videos"] if is_live(v)]

# 1. JS data for the browser (all videos; the page decides live vs coming soon at runtime).
public_fields = ("key", "youtube_id", "type", "letter", "title", "publish_at")
js_videos = [{k: v.get(k, "") for k in public_fields} for v in data["videos"]]
(ROOT / "js/videos-data.js").write_text(
    "// Generated by tools/build.py from data/videos.json. Do not edit by hand.\n"
    f"window.CHANNEL = {json.dumps(ch, ensure_ascii=False)};\n"
    f"window.CHANNEL_VIDEOS = {json.dumps(js_videos, ensure_ascii=False, indent=1)};\n",
    encoding="utf-8",
)

# 2. JSON-LD
graph = [
    {
        "@type": "Organization",
        "@id": site + "#org",
        "name": ch["name"],
        "url": site,
        "logo": site + "icons/icon-512.png",
        "sameAs": [ch["url"]],
    },
    {
        "@type": "WebSite",
        "@id": site + "#website",
        "name": ch["name"],
        "url": site,
        "inLanguage": "en",
        "publisher": {"@id": site + "#org"},
    },
    {
        "@type": "WebPage",
        "@id": site + "#page",
        "url": site,
        "name": "English with Ms Tuyen | Fun English Phonics & Letter Tracing for Kids",
        "isPartOf": {"@id": site + "#website"},
        "about": {"@id": site + "#org"},
        "primaryImageOfPage": site + "img/og-image.jpg",
    },
]
for v in live:
    item = {
        "@type": "VideoObject",
        "name": v["title"],
        "description": f"{v['title']}. Learn English with Poppy the rabbit on English with Ms Tuyen.",
        "thumbnailUrl": f"https://i.ytimg.com/vi/{v['youtube_id']}/hqdefault.jpg",
        "uploadDate": v["publish_at"],
        "contentUrl": watch_url(v),
        "embedUrl": f"https://www.youtube-nocookie.com/embed/{v['youtube_id']}",
        "inLanguage": "en",
        "isFamilyFriendly": True,
        "publisher": {"@id": site + "#org"},
    }
    if v.get("duration"):
        item["duration"] = v["duration"]
    graph.append(item)
jsonld = json.dumps({"@context": "https://schema.org", "@graph": graph}, ensure_ascii=False, indent=1)

# 3. Static crawlable video list (also shown without JavaScript).
if live:
    items = "\n".join(
        f'            <li><a href="{html.escape(watch_url(v))}" rel="noopener" target="_blank">{html.escape(v["title"])}</a></li>'
        for v in live
    )
else:
    items = '            <li>New lessons are coming soon. <a href="' + ch["url"] + '">Visit our YouTube channel</a>.</li>'


def replace_block(text, name, body):
    pat = re.compile(rf"(<!-- BUILD:{name} -->).*?(<!-- /BUILD:{name} -->)", re.S)
    if not pat.search(text):
        raise SystemExit(f"marker BUILD:{name} missing in index.html")
    return pat.sub(lambda m: f"{m.group(1)}\n{body}\n    {m.group(2)}", text)


index = ROOT / "index.html"
text = index.read_text(encoding="utf-8")
text = replace_block(text, "JSONLD", f'    <script type="application/ld+json">\n{jsonld}\n    </script>')
text = replace_block(text, "VIDEOLIST", items)
index.write_text(text, encoding="utf-8")

# 4. sitemap
(ROOT / "sitemap.xml").write_text(
    '<?xml version="1.0" encoding="UTF-8"?>\n'
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
    f"  <url><loc>{site}</loc><lastmod>{now.date().isoformat()}</lastmod></url>\n"
    "</urlset>\n",
    encoding="utf-8",
)

print(f"videos: {len(data['videos'])} total, {len(live)} live in JSON-LD")
